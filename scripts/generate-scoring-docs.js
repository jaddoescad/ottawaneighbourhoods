#!/usr/bin/env node
/**
 * Regenerates the scoring section of CLAUDE.md from src/data/scoring-config.json
 * (between the scoring:start / scoring:end markers).
 *
 * Usage: node scripts/generate-scoring-docs.js [--check]
 *   --check  exit 1 if CLAUDE.md is out of date instead of rewriting it
 */

const fs = require('fs');
const path = require('path');

const CONFIG_PATH = path.join(__dirname, '..', 'src', 'data', 'scoring-config.json');
const DOC_PATH = path.join(__dirname, '..', 'CLAUDE.md');
const START = '<!-- scoring:start (generated by scripts/generate-scoring-docs.js; edit src/data/scoring-config.json instead) -->';
const END = '<!-- scoring:end -->';

const pct = (v) => `${Math.round(v * 100)}%`;

function renderScoringDocs(config) {
  const total = config.categories.reduce((s, c) => s + c.weight, 0);
  const p = config.parameters;
  const lines = [];
  lines.push('## Scoring Model');
  lines.push('');
  lines.push(`Single source of truth: \`src/data/scoring-config.json\` (v${config.version}). The pipeline (\`scripts/lib/scoring.js\`), the UI (\`src/lib/scoring.ts\`), the /methodology page and this section all read it.`);
  lines.push('');
  lines.push(config.summary);
  lines.push('');
  lines.push('- Metric score: piecewise-linear between fixed `[value, score]` breakpoints, clamped. Missing input is `null`, never 0.');
  lines.push(`- Category score: weighted mean of metrics with data. \`categoryCoverage\` = share of metric weight with data; below ${pct(p.minCategoryCoverage)} (or the category's \`minCoverage\`) the category is \`null\`, left out of the overall score, and \`scoreIncomplete\` is set.`);
  lines.push('- Overall score: weighted mean of the rounded category scores (renormalized over available categories).');
  lines.push(`- Count-based rates (crime, overdose, collisions) use symmetric shrinkage: \`(count + k × cityRate) / (exposure + k)\`, k = ${p.shrinkagePersonYears} person-years (${p.shrinkageRoadKmYears} road-km-years for collisions).`);
  lines.push(`- Rank: competition ranking on the rounded overall score (ties share a rank). \`rankRange\` = p${Math.round(p.rankRangePercentiles[0] * 100)}–p${Math.round(p.rankRangePercentiles[1] * 100)} rank over ${p.rankSimulations} runs with each category weight × U(${1 - p.rankWeightJitter}, ${1 + p.rankWeightJitter}). \`tier\`: ${config.tiers.map((t) => t.label).join(' / ')}.`);
  lines.push(`- Score labels: ${config.scoreLabels.map((l) => `${l.label} ${l.min}+`).join(', ')}.`);
  lines.push('- Distances and access shares are measured from residential address points (`src/data/csv/residential_grid.csv`), weighted by population.');
  lines.push('');
  lines.push('| Category | Weight | Metrics (weight within category) |');
  lines.push('|---|---|---|');
  for (const c of config.categories) {
    const mt = c.metrics.reduce((s, m) => s + m.weight, 0);
    lines.push(`| ${c.label} (\`${c.key}\`) | ${pct(c.weight / total)} | ${c.metrics.map((m) => `${m.label} ${pct(m.weight / mt)}`).join('; ')} |`);
  }
  lines.push('');
  lines.push('### Metric definitions');
  lines.push('');
  for (const c of config.categories) {
    for (const m of c.metrics) {
      const bps = [...m.breakpoints].sort((a, b) => a[0] - b[0]).map(([v, s]) => `${v}→${s}`).join(', ');
      lines.push(`- **${m.key}** (${c.label}; ${m.unit}; ${m.direction} is better): ${m.description} Breakpoints: ${bps}. Source: ${m.source}.`);
    }
  }
  lines.push('');
  lines.push('### Shown but not scored');
  lines.push('');
  for (const ctx of config.context) lines.push(`- **${ctx.key}**: ${ctx.label}. ${ctx.description}`);
  lines.push('');
  lines.push('### Presets (home page "Customize")');
  lines.push('');
  for (const pr of config.presets) {
    lines.push(`- **${pr.label}**: ${config.categories.map((c) => `${c.key} ${pct(pr.weights[c.key])}`).join(', ')}`);
  }
  lines.push('');
  lines.push('### Checks');
  lines.push('');
  lines.push('```bash');
  lines.push('node scripts/check-scoring.js            # config sanity, data integrity, docs in sync, validation correlations');
  lines.push('node scripts/compare-scores.js <before.json> [--out file.md]   # before/after scores and ranks');
  lines.push('node scripts/generate-scoring-docs.js    # rewrite this section after editing the config');
  lines.push('```');
  return lines.join('\n');
}

function updatedDoc(doc, config) {
  const block = `${START}\n${renderScoringDocs(config)}\n${END}`;
  const s = doc.indexOf('<!-- scoring:start');
  const e = doc.indexOf(END);
  if (s === -1 || e === -1) throw new Error('CLAUDE.md is missing the scoring:start / scoring:end markers');
  return doc.slice(0, s) + block + doc.slice(e + END.length);
}

module.exports = { renderScoringDocs, updatedDoc, DOC_PATH, CONFIG_PATH };

if (require.main === module) {
  const config = JSON.parse(fs.readFileSync(CONFIG_PATH, 'utf8'));
  const doc = fs.readFileSync(DOC_PATH, 'utf8');
  const next = updatedDoc(doc, config);
  if (process.argv.includes('--check')) {
    if (next !== doc) {
      console.error('CLAUDE.md scoring section is out of date. Run: node scripts/generate-scoring-docs.js');
      process.exit(1);
    }
    console.log('CLAUDE.md scoring section is up to date.');
  } else {
    fs.writeFileSync(DOC_PATH, next);
    console.log(next === doc ? 'CLAUDE.md already up to date.' : 'Updated CLAUDE.md scoring section.');
  }
}
